// Ambiguity policy: a word is excluded if it has a second, comparably
// common everyday reading as a DIFFERENT part of speech (e.g. "fly" —
// insect noun vs. to fly; "watch" — wristwatch noun vs. to watch;
// "clean" — tidy adjective vs. to clean). Different MEANINGS of the same
// part of speech (e.g. "bank" — riverbank vs. financial bank, both
// nouns) are not ambiguous for this game and are fine to include.
// noun/verb/adjective favor word families that are structurally
// one-directional in English (e.g. -en/-ify/-ize verbs, -ous/-ful/-ible/
// -ive adjectives, -tion/-ness/-ity/-ment nouns) — these essentially
// never double as a different part of speech in ordinary usage. That
// bias skews long, so each category also has a deliberate short-word
// pass (3-4 letters — animals, food, small objects, -y adjectives, short
// Latinate/monosyllabic verbs) vetted against the same ambiguity policy,
// so a maxWordLength setting has enough pool left at low values to be
// useful for younger kids.
//
// gerund/participle are intentionally left as originally curated: by
// definition every -ing gerund is spelled identically to a present
// participle, and every -ed/-en participle is spelled identically to a
// past-tense verb form. Shown as a single word with no sentence, that
